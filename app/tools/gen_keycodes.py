#!/usr/bin/env python3
"""Generate app/src/keycodes/tables_gen.cpp from the Python app's keycode tables.

Run from the repo root with the Python app's venv: venv/bin/python app/tools/gen_keycodes.py
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(ROOT, "src", "main", "python"))

from keycodes import keycodes as K  # noqa: E402
from keycodes.keycodes_v5 import keycodes_v5  # noqa: E402
from keycodes.keycodes_v6 import keycodes_v6  # noqa: E402
from keymaps import KEYMAPS  # noqa: E402

OUT = os.path.join(ROOT, "app", "src", "keycodes", "tables_gen.cpp")

GROUPS = [
    ("Special", K.KEYCODES_SPECIAL),
    ("Basic", K.KEYCODES_BASIC),
    ("Shifted", K.KEYCODES_SHIFTED),
    ("Iso", K.KEYCODES_ISO),
    ("Boot", K.KEYCODES_BOOT),
    ("Modifiers", K.KEYCODES_MODIFIERS),
    ("Quantum", K.KEYCODES_QUANTUM),
    ("Backlight", K.KEYCODES_BACKLIGHT),
    ("Media", K.KEYCODES_MEDIA),
    ("MacroBase", K.KEYCODES_MACRO_BASE),
    ("MidiBasic", K.KEYCODES_MIDI_BASIC),
    ("MidiAdvanced", K.KEYCODES_MIDI_ADVANCED),
    # subsets of the above, for the keycode tabs
    ("BasicNumpad", K.KEYCODES_BASIC_NUMPAD),
    ("BasicNav", K.KEYCODES_BASIC_NAV),
    ("IsoKr", K.KEYCODES_ISO_KR),
]


def s(v):
    if v is None:
        return "nullptr"
    out = ""
    for ch in v:
        if ch == "\\":
            out += "\\\\"
        elif ch == '"':
            out += '\\"'
        elif ch == "\n":
            out += "\\n"
        else:
            out += ch
    return '"' + out + '"'


def main():
    lines = [
        "// Generated by app/tools/gen_keycodes.py from src/main/python/keycodes and keymaps.py; do not edit.",
        '#include "keycodes/tables.h"',
        "",
        "namespace keycodes::tables {",
        "",
    ]
    for name, group in GROUPS:
        lines.append("static const KeycodeDef k{}[] = {{".format(name))
        for kc in group:
            aliases = "|".join(kc.alias[1:])
            recorder = "|".join(a for a, v in K.Keycode.recorder_alias_to_keycode.items() if v is kc)
            lines.append("    {{{}, {}, {}, {}, {}, {}, {}, {}}},".format(
                s(kc.qmk_id), s(kc.label), s(kc.tooltip), "true" if kc.masked else "false", s(kc.printable),
                s(aliases), s(recorder), s(kc.requires_feature)))
        if not group:
            lines.append("    {nullptr, nullptr, nullptr, false, nullptr, nullptr, nullptr, nullptr},")
        lines.append("};")
        lines.append("")
    lines.append("const QList<GroupDef> &groups()")
    lines.append("{")
    lines.append("    static const QList<GroupDef> g = {")
    for name, group in GROUPS:
        lines.append("        {{Group::{0}, k{0}, {1}}},".format(name, len(group)))
    lines.append("    };")
    lines.append("    return g;")
    lines.append("}")
    lines.append("")
    for proto, table in (("5", keycodes_v5.kc), ("6", keycodes_v6.kc)):
        lines.append("static const RawCode kV{}[] = {{".format(proto))
        for name, val in table.items():
            lines.append("    {{{}, 0x{:X}}},".format(s(name), val))
        lines.append("};")
        lines.append("")
    lines.append("std::span<const RawCode> rawCodes(int protocol)")
    lines.append("{")
    lines.append("    if (protocol == 6)")
    lines.append("        return kV6;")
    lines.append("    return kV5;")
    lines.append("}")
    lines.append("")
    for i, (title, mapping) in enumerate(KEYMAPS):
        lines.append("static const KeymapLabel kMap{}[] = {{".format(i))
        for qmk_id, label in mapping.items():
            lines.append("    {{{}, {}}},".format(s(qmk_id), s(label)))
        if not mapping:
            lines.append("    {nullptr, nullptr},")
        lines.append("};")
    lines.append("")
    lines.append("const QList<KeymapDef> &keymaps()")
    lines.append("{")
    lines.append("    static const QList<KeymapDef> k = {")
    for i, (title, mapping) in enumerate(KEYMAPS):
        lines.append("        {{{}, kMap{}, {}}},".format(s(title), i, len(mapping)))
    lines.append("    };")
    lines.append("    return k;")
    lines.append("}")
    lines.append("")
    lines.append("}")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(OUT)


if __name__ == "__main__":
    main()
